class User {
  final String id;
  final String name;
  final String avatarUrl;
  final String email;
  final String phone;
  final bool isSeller;

  User({
    required this.id,
    required this.name,
    required this.avatarUrl,
    required this.email,
    required this.phone,
    required this.isSeller,
  });
}
